        cards.scryfall_id NOT IN ('bc9c39d1-1e10-4cd3-a4b1-b6eb7c1a0b65') AS after_order_lead,
        COALESCE(blob.variation, false) AS is_variation,
        COALESCE(cards.collector_number_int, 0) AS number,

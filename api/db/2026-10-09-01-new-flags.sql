-- Scryfall's `new:<value>` finds the printings that are the FIRST with something: `new:card` a
-- card's first printing on paper, `new:frame` its first in each frame, `new:foil` and `new:nonfoil`
-- its first paper printing in that finish, `new:art` the first printing anywhere of an artwork.
-- "First" is over other printings, which no row can see at query time, so -- like `new:rarity` in
-- 2026-10-04-03 -- the answers are decided when the data is written.
--
-- One smallint per printing, one bit a value (NEW_FLAG_BITS in api/parsing/db_info.py): 1 card,
-- 2 frame, 64 foil, 128 nonfoil, 512 art. The bit numbers leave room for the values Scryfall
-- honours that this table cannot answer yet (a card's first printing in a digital game, with a
-- flavor text, in a language). A printing's bit is set when it is the first of its group among the
-- eligible rows, by (release date, release batch, variation last, the collector number's digits as
-- one integer, Scryfall id). Each negation is the complement. NULL means "not yet computed" and
-- answers neither a keyword nor its negation.
--
-- Maintained by _sync_new_flags in api/admin_resource.py after every import -- a new printing can
-- take a flag from the one that held it -- and backfilled once below so the keywords answer as
-- soon as this deploys rather than after the next import. _build_new_flags_sql's docstring carries
-- the measured rule; the statement below IS that statement (a test compares them), with the
-- October release batches of api/release_batches.py inlined.
ALTER TABLE magic.cards ADD COLUMN IF NOT EXISTS new_flags smallint;

COMMENT ON COLUMN magic.cards.new_flags IS 'Printing-level: the answers to Scryfall''s `new:card` (bit 1), `new:frame` (2), `new:foil` (64), `new:nonfoil` (128) and `new:art` (512) -- this printing is the first of its group (the card; the card and frame; the card in a finish; the artwork, across cards) by release date, release batch, variation last, the collector number''s digits as one integer, Scryfall id; memorabilia outside. NULL until computed.';


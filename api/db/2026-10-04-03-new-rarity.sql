-- Scryfall's `new:rarity` finds the printings that are the FIRST of their card at their rarity.
-- "First" is over the card's other printings, which no row can see at query time, so -- like the
-- count columns of 2026-10-04-01 and the cheapest codes of 2026-10-04-02 -- the answer is decided
-- when the data is written.
--
-- One boolean per printing: true when it is the first of its card (oracle id) at its rarity, by
-- (release date, release batch, first integer of the collector number, variation last, Scryfall
-- id), among the printings outside the promo, memorabilia, from_the_vault and treasure_chest set
-- types and outside every masterpiece set but `wot`. Its negation is the complement. NULL means
-- "not yet computed" and answers neither the keyword nor its negation.
--
-- Maintained by _sync_new_rarity in api/admin_resource.py after every import -- a new printing can
-- take the flag from the one that held it -- and backfilled once below so the keyword answers as
-- soon as this deploys rather than after the next import. _build_new_rarity_sql's docstring
-- carries the measured rule; the statement below IS its unchunked form (a test compares them), with
-- the release batches of api/release_batches.py inlined.
ALTER TABLE magic.cards ADD COLUMN IF NOT EXISTS new_rarity boolean;

COMMENT ON COLUMN magic.cards.new_rarity IS 'Printing-level: the answer to Scryfall''s `new:rarity` -- this printing is the first of its card at its rarity (by release date, release batch, first integer of the collector number, variation last, Scryfall id; outside the promo, memorabilia, from_the_vault and treasure_chest set types and every masterpiece set but wot). NULL until computed.';


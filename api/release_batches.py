"""The order Scryfall gives the SETS that share one release date, measured -- what `new:rarity` needs.

`new:rarity` is the first printing of a card at its rarity, and "first" is decided by release date.
Printings of one card released the same day are then ordered by their SET, and that order is not
anything Scryfall publishes: no `/sets` field, no parent/child or set-type rule, and not the set
code reproduces it (and it is not one order over the sets: `prm` sorts before `sld` on 2020-07-31
and after it on 2022-11-04). What is regular is its shape -- a date's sets are the code order cut
into BATCHES, each alphabetical, one after another (2025-04-11 is `plg25 plst pspl spg tdm | tdc |
atdm ptdm ttdc ttdm`) -- so the table stores, per date, the batch of every set that is NOT in the
first one, and a date's sets sort by (batch, code). A (date, set) not listed is batch 0. `new:rarity`
reads the batch alone: after it the collector number and the Scryfall id decide, never the code.

Measured on api.scryfall.com in September 2026, one request per date on which two or more sets
released (`order=released` over one printing of each set, extras and variations in). It is a
snapshot of an order Scryfall does not promise to keep, and it decides only same-day ties inside
one card's own printings at one rarity: of the 38,943 printings `new:rarity` holds there, 18
groups (36 printings) are wrong without it, and none with it (checked against the whole list on
2026-10-04). Refresh it by re-measuring the dates whose groups come out wrong; the sync reads it on
every import, and a new migration is only needed to backfill sooner than the next import.

Rows are `(yyyymmdd, set code, batch)`.
"""

